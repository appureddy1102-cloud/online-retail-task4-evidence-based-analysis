md('''## 9. Manual Welch comparison: one AOV per identified customer
The comparison is exploratory and conditional on sampling/independence assumptions.
Unequal variances are allowed; confounding, heavy tails and missingness are not solved.
The difference is not a causal effect of geography.''')
code("""a = customers.loc[customers.Country.eq('United Kingdom'), 'AOV'].to_numpy(float)
b = customers.loc[~customers.Country.eq('United Kingdom'), 'AOV'].to_numpy(float)
v1, v2 = a.var(ddof=1), b.var(ddof=1)
se = np.sqrt(v1/len(a)+v2/len(b))
t = (a.mean()-b.mean())/se
df = (v1/len(a)+v2/len(b))**2 / ((v1/len(a))**2/(len(a)-1)
                                 +(v2/len(b))**2/(len(b)-1))
p = 2*stats.t.sf(abs(t), df)
print('n:', len(a), len(b), '| means:', a.mean(), b.mean())
print('variances:', v1, v2, '| standard error:', se)
print('t:', t, '| Welch df:', df, '| two-sided p:', p)
print('95% interval, UK minus non-UK:', e['welch_mean_difference_ci95'])
assert np.isclose(t, stats.ttest_ind(a, b, equal_var=False).statistic)
assert np.isclose(p, stats.ttest_ind(a, b, equal_var=False).pvalue)
print('Repeat vs one-time customer-AOV results:')
display(pd.Series(m['welch_repeat_onetime_customer_aov']))""")
